// The Logical Reasoning hub reuses questions that already ship inside exam
// mocks (see REASONING_SHARE_SOURCES in exams.ts for the existing precedent
// that pure reasoning is exam-agnostic). Nothing here duplicates question
// content: only IDs are listed, and the hub resolves them against the same
// wired banks the exam mocks use.
//
// Grades are the hub's OWN absolute scale, deliberately not the per-exam
// `difficulty` tag on the source question. Those tags sort by topic rather
// than by effort — Seating questions are tagged hard almost by default and
// Venn questions easy almost by default — so they are unusable for a
// cross-exam difficulty ladder. The hub rubric is:
//   easy   — one step, no case analysis
//   medium — two to four linked steps, or one construction, no branching
//   hard   — branching and elimination, interleaved rules, layered codes,
//            or a sufficiency trap
//
// Test IDs are permanent. A published set's question list is never edited:
// its URL is indexed and visitors hold saved attempts against it, so new
// material becomes a new set rather than a revision of an existing one.

