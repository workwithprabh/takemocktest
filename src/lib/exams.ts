export const EXAM_LIST = Object.values(EXAMS);

export function getExam(slug: string): ExamConfig | undefined {
  return EXAMS[slug as ExamSlug];
}

export function getTestConfig(exam: ExamConfig, testId: string) {
  for (const stage of exam.stages) {
    const test = stage.tests.find((item) => item.id === testId);
    if (test) return { stage, test };
  }
}

export function getExamSections(exam: ExamConfig): string[] {
  return [...new Set(exam.stages.flatMap((stage) => stage.pattern.sections))];
}

export function getCheckedTestCount(exam: ExamConfig): number {
  return exam.stages.flatMap((stage) => stage.tests).filter((test) => test.status === 'checked').length;
}

export const COUNTRIES = ['in'] as const;
export type CountrySlug = (typeof COUNTRIES)[number];

export function getAllTestSlugs(exam: ExamConfig): string[] {
  return exam.stages.flatMap((stage) => stage.tests.map((test) => test.id));
}

const ACRONYMS = new Set(['cbt']);

export function testIdToName(testId: string): string {
  return testId
    .split('-')
    .map((word) => {
      if (/^\d+$/.test(word)) return word;
      if (ACRONYMS.has(word.toLowerCase())) return word.toUpperCase();
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join(' ');
}
