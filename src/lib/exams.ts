export type TestStatus = 'checked' | 'demo';

export interface TestConfig {
  id: string;
  name: string;
  kind: 'full-length' | 'sectional' | 'practice' | 'quick' | 'topic' | 'difficulty';
  status: TestStatus;
  duration: number;
  sectionDuration?: number;
  sectionDurations?: number[];
  marksPerCorrect: number;
  negativeMarking: number;
  scoringNote?: string;
  section?: string;
  checkedOn?: string;
}

export interface StagePattern {
  status: 'official' | 'review-pending';
  cycle?: string;
  sections: string[];
  totalQuestions?: number;
  totalMarks?: number;
  duration?: number;
  negativeMarking?: number | string;
  sectionBreakdown?: {
    name: string;
    questions: number;
    marks: number;
    duration?: number;
  }[];
  timerNote?: string;
  note?: string;
  sourceUrl?: string;
  checkedOn?: string;
}

export interface TestStage {
  id: string;
  name: string;
  pattern: StagePattern;
  tests: TestConfig[];
}

export interface ExamConfig {
  slug: ExamSlug;
  name: string;
  /** Shorter variant of `name`, used only in <title> tags where the full name would push past ~60-65 characters. Falls back to `name` when absent. */
  shortName?: string;
  fullName: string;
  category: 'SSC' | 'Banking' | 'Railways' | 'Civil Services' | 'Engineering';
  stages: TestStage[];
}

