export function getQuestionsForTest(examSlug: string, testId: string): Question[] {
  const checkedBank = CHECKED_TEST_BANKS[`${examSlug}/${testId}`];
  if (checkedBank) return checkedBank;

  // Demo sets reuse the old sample bank. They are labelled as demos in the UI
  // and must not be presented as complete or officially sourced papers.
  const bank = QUESTION_BANK[examSlug as ExamSlug] ?? [];
  if (bank.length === 0) return [];
  const match = testId.match(/(\d+)$/);
  const testNum = match ? parseInt(match[1], 10) : 1;
  const offset = ((testNum - 1) * 5) % bank.length;
  return [...bank.slice(offset), ...bank.slice(0, offset)];
}

